import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

test('PWA manifest and asset configuration', async t => {
  await t.test('public directory contains required icons and favicon', () => {
    const faviconPath = path.resolve('public/favicon.svg');
    const pwa192Path = path.resolve('public/pwa-192x192.png');
    const pwa512Path = path.resolve('public/pwa-512x512.png');
    const appleIconPath = path.resolve('public/apple-touch-icon.png');

    assert.equal(fs.existsSync(faviconPath), true, 'favicon.svg must exist');
    assert.equal(fs.existsSync(pwa192Path), true, 'pwa-192x192.png must exist');
    assert.equal(fs.existsSync(pwa512Path), true, 'pwa-512x512.png must exist');
    assert.equal(fs.existsSync(appleIconPath), true, 'apple-touch-icon.png must exist');

    // Verify PNG header signature (0x89 0x50 0x4E 0x47)
    const pngHeader = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
    const pwa192Bytes = fs.readFileSync(pwa192Path).subarray(0, 8);
    const pwa512Bytes = fs.readFileSync(pwa512Path).subarray(0, 8);
    assert.deepEqual(pwa192Bytes, pngHeader, 'pwa-192x192.png has valid PNG signature');
    assert.deepEqual(pwa512Bytes, pngHeader, 'pwa-512x512.png has valid PNG signature');
  });

  await t.test('index.html contains PWA meta tags and links', () => {
    const indexHtml = fs.readFileSync('index.html', 'utf8');
    assert.match(indexHtml, /<meta\s+name=["']theme-color["']/i, 'index.html has theme-color meta');
    assert.match(indexHtml, /<meta\s+name=["']apple-mobile-web-app-capable["']/i, 'index.html has apple-mobile-web-app-capable');
    assert.match(indexHtml, /<link\s+rel=["']apple-touch-icon["']/i, 'index.html has apple-touch-icon link');
    assert.match(indexHtml, /<link\s+rel=["']icon["']/i, 'index.html has icon link');
  });

  await t.test('dist build outputs manifest and service worker', () => {
    // If build has been run, dist should contain sw.js and manifest.webmanifest
    if (fs.existsSync('dist')) {
      const swExists = fs.existsSync('dist/sw.js');
      const manifestExists = fs.existsSync('dist/manifest.webmanifest');
      assert.equal(swExists, true, 'dist/sw.js generated by VitePWA');
      assert.equal(manifestExists, true, 'dist/manifest.webmanifest generated by VitePWA');

      const manifestContent = JSON.parse(fs.readFileSync('dist/manifest.webmanifest', 'utf8'));
      assert.equal(manifestContent.display, 'standalone');
      assert.equal(manifestContent.name, '鉄道鬼ごっこ - TRANSIT TAG');
      assert.equal(manifestContent.short_name, '鉄道鬼ごっこ');
      assert.equal(manifestContent.theme_color, '#0f172a');
      assert.ok(manifestContent.icons.length >= 2, 'manifest defines multiple icons');
    }
  });

  await t.test('OSM tile caching pattern matches legitimate tiles and rejects malicious domains', () => {
    const tilePattern = /^https:\/\/[a-c]\.tile\.openstreetmap\.org\/.*/i;
    assert.equal(tilePattern.test('https://a.tile.openstreetmap.org/13/7200/3200.png'), true);
    assert.equal(tilePattern.test('https://b.tile.openstreetmap.org/13/7200/3200.png'), true);
    assert.equal(tilePattern.test('https://c.tile.openstreetmap.org/13/7200/3200.png'), true);
    assert.equal(tilePattern.test('https://evil.com/fake.tile.openstreetmap.org/test.png'), false);
    assert.equal(tilePattern.test('https://attacker-tile.openstreetmap.org/test.png'), false);
    assert.equal(tilePattern.test('http://a.tile.openstreetmap.org/test.png'), false);
  });
});
